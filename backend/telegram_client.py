async def daily_digest_scheduler(client):
    while True:
        try:
            now = datetime.now(kyiv_tz)
            target = now.replace(hour=8, minute=0, second=0, microsecond=0)
            if now >= target:
                target += timedelta(days=1)
            wait_seconds = (target - now).total_seconds()
            print(f"⏰ [DailyDigest] Наступний ранковий брифінг о {target.strftime('%d.%m.%Y %H:%M')} (через {int(wait_seconds // 60)} хв)")
            await asyncio.sleep(wait_seconds)

            digest = await generate_morning_digest()
            digest_text = digest.get("text", "")
            if digest_text and client and client.is_connected():
                try:
                    await client.send_message('me', digest_text)
                    print("✅ [DailyDigest] Ранковий брифінг успішно надіслано в 'Збережені повідомлення'!")
                except Exception as e:
                    print(f"⚠️ [DailyDigest] Не вдалося надіслати дайджест у Telegram: {e}")
            await asyncio.sleep(60)
        except asyncio.CancelledError:
            break
        except Exception as e:
            print(f"⚠️ [DailyDigest] Помилка планувальника: {e}")
            await asyncio.sleep(60)

