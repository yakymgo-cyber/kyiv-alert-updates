def update_night_summary_from_messages(messages):
    global night_summary
    now = datetime.now(timezone.utc)
    cutoff = now - timedelta(hours=10)
    
    total_threats = 0
    uav_count = 0
    missile_count = 0
    ppo_mentions = 0
    last_clear_time = None
    
    ppo_keywords = ["ппо", "працює ппо", "робота ппо", "роботі ппо", "збиття", "збито", "мінус", "ліквідовано"]
    clear_keywords = ["відбій", "чисто", "тихо", "дорозвідка", "локаційно втрачено", "немає цілей"]
    
    for msg in messages:
        raw_date = msg.get("date")
        if not raw_date:
            continue
        try:
            m_date = datetime.fromisoformat(raw_date)
            if m_date.tzinfo is None:
                m_date = m_date.replace(tzinfo=timezone.utc)
            else:
                m_date = m_date.astimezone(timezone.utc)
        except Exception:
            continue
            
        if m_date < cutoff:
            continue
            
        text = msg.get("text", "")
        text_lower = text.lower()
        
        threats = msg.get("threats") or []
        for t in threats:
            total_threats += 1
            t_type = str(t.get("type", "shahed")).lower()
            if any(k in t_type for k in ["missile", "ballistic", "hypersonic", "supersonic", "cruise", "kab"]):
                missile_count += 1
            else:
                uav_count += 1
                
        if any(pk in text_lower for pk in ppo_keywords):
            ppo_mentions += 1
            
        if msg.get("type") == "clear" or any(ck in text_lower for ck in clear_keywords):
            if last_clear_time is None:
                last_clear_time = raw_date
            else:
                try:
                    cur_clear_dt = datetime.fromisoformat(last_clear_time)
                    if cur_clear_dt.tzinfo is None:
                        cur_clear_dt = cur_clear_dt.replace(tzinfo=timezone.utc)
                    if m_date > cur_clear_dt:
                        last_clear_time = raw_date
                except Exception:
                    last_clear_time = raw_date
                    
    night_summary["total_threats"] = total_threats
    night_summary["uav_count"] = uav_count
    night_summary["missile_count"] = missile_count
    night_summary["ppo_mentions"] = ppo_mentions
    night_summary["last_clear_time"] = last_clear_time
    night_summary["last_updated"] = now.isoformat()
    return night_summary

def clean_message(text):
    text = re.sub(r'http\S+', '', text)
    text = re.sub(r'@\w+', '', text)
    
    ad_markers = [
        "підписатись", "наш резерв", "надіслати новину", 
        "джерело", "більше новин", "реклама", "зв'язок з", 
        "підписка", "канал"
    ]
    
    lines = text.split('\n')
    clean_lines = []
    
    for line in lines:
        lower_line = line.lower()
        if any(marker in lower_line for marker in ad_markers):
            continue 
        if line.strip():
            clean_lines.append(line.strip())
            
    return '\n'.join(clean_lines)

def extract_altitude(text):
    t_lower = text.lower()
    # Explicit meters: (\d{3,4})\s*(?:м|метр|m)(?![а-яіїєґa-z])
    m = re.search(r'(\d{3,4})\s*(?:м|метр|m)(?![а-яіїєґa-z])', t_lower)
    if m:
        try:
            return int(m.group(1))
        except ValueError:
            pass
    # Separate 3/4-digit numbers in range 300..7500 divisible by 10
    tokens = re.findall(r'\b(\d{3,4})\b', text)
    for tok in tokens:
        try:
            val = int(tok)
            if 300 <= val <= 7500 and val % 10 == 0:
                return val
        except ValueError:
            pass
    return None

