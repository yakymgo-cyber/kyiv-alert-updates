def stem_location_name(word: str) -> str:
    lower = word.lower()
    vowels = {'а', 'я', 'у', 'ю', 'і', 'и', 'о', 'е'}
    if len(lower) >= 6 and lower[-1] in vowels:
        lower = lower[:-1]
    return lower

def _save_to_remote_config(stem: str, lat: float, lon: float, name: str):
    try:
        import json
        cfg = {}
        if os.path.exists(REMOTE_CONFIG_PATH):
            with open(REMOTE_CONFIG_PATH, "r", encoding="utf-8") as f:
                cfg = json.load(f)
        if "extra_locations" not in cfg:
            cfg["extra_locations"] = {}
        cfg["extra_locations"][stem] = {
            "lat": round(lat, 5),
            "lon": round(lon, 5),
            "name": name
        }
        with open(REMOTE_CONFIG_PATH, "w", encoding="utf-8") as f:
            json.dump(cfg, f, ensure_ascii=False, indent=2)
    except Exception as e:
        print(f"⚠️ Не вдалося зберегти нову локацію в remote_config.json: {e}")

async def auto_geocode_location(raw_word: str, stem: str):
    params = {
        "format": "json",
        "q": f"{raw_word}, Київська область",
        "viewbox": "29.2,51.6,32.2,49.1",
        "bounded": 1,
        "limit": 1,
        "accept-language": "uk"
    }
    try:
        async with httpx.AsyncClient(timeout=5.0) as client:
            resp = await client.get(
                "https://nominatim.openstreetmap.org/search",
                params=params,
                headers={"User-Agent": "ua.kyiv.alert.monitor/1.0 (contact: admin@kyivalert.ua)"}
            )
            if resp.status_code == 200:
                data = resp.json()
                if isinstance(data, list) and len(data) > 0:
                    item = data[0]
                    lat = float(item["lat"])
                    lon = float(item["lon"])
                    if 49.1 <= lat <= 51.6 and 29.2 <= lon <= 32.2:
                        disp_name = item.get("display_name", raw_word).split(",")[0].strip() or raw_word
                        KYIV_LOCATIONS[stem] = (lat, lon, disp_name)
                        _save_to_remote_config(stem, lat, lon, disp_name)
                        print(f"🗺️ [Auto-Discovery] Вивчено локацію: {disp_name} ({stem}) -> {lat}, {lon}")
    except Exception as e:
        print(f"⚠️ Помилка авто-геокодування {raw_word}: {e}")

def _check_and_auto_geocode_locations(text: str):
    candidate_regex = re.compile(
        r'(?:на|через|біля|поблизу|район[іу]?|повз|від|з|із|в бік|у бік|курсом на|вектор на)\s+([А-ЯІЇЄҐ][а-яіїєґ\x27ʼ\-]{3,})'
    )
    for m in candidate_regex.finditer(text):
        raw_word = m.group(1)
        raw_lower = raw_word.lower()
        if raw_lower in LOCATION_STOP_WORDS:
            continue
        stem = stem_location_name(raw_word)
        if stem not in KYIV_LOCATIONS and stem not in pending_or_failed_geocodes:
            pending_or_failed_geocodes.add(stem)
            try:
                loop = asyncio.get_running_loop()
                loop.create_task(auto_geocode_location(raw_word, stem))
            except RuntimeError:
                import threading
                threading.Thread(target=lambda rw=raw_word, st=stem: asyncio.run(auto_geocode_location(rw, st)), daemon=True).start()

